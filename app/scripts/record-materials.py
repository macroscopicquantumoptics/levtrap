"""Write src/engine/materials.ts from levtrap.materials (run by `npm run record`).

The app shows a material's n, k, density and source as soon as it is
picked, before the engine has answered; materials.test.ts checks this copy
against the Python module.
"""

import json
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root / "src"))
from levtrap.materials import MATERIALS  # noqa: E402

data = {
    name: dict(density=m.density, table=[[wl, complex(n).real, complex(n).imag] for wl, n in m.table.items()],
               sellmeier=list(m.sellmeier) if m.sellmeier else None, sellmeier_range=list(m.sellmeier_range),
               source=m.source)
    for name, m in MATERIALS.items()
}
out = root / "app" / "src" / "engine" / "materials.ts"
out.write_text(f"""// Generated by `npm run record` (scripts/record-materials.py) from levtrap.materials. Do not edit.
/**
 * Material presets: refractive index n + ik and density, with their source.
 * getMaterial mirrors levtrap.materials.get_material (materials.test.ts
 * compares them).
 */

export interface MaterialData {{
  /** kg/m³ */
  density: number;
  /** [wavelength m, n, k] */
  table: [number, number, number][];
  /** Sellmeier (B1, C1, B2, C2, B3, C3), C in µm² */
  sellmeier: number[] | null;
  /** m */
  sellmeier_range: [number, number];
  source: string;
}}

export const MATERIALS: Record<string, MaterialData> = {json.dumps(data, indent=2)};

export const MATERIAL_NAMES = Object.keys(MATERIALS);

export interface MaterialAt {{
  n: number;
  k: number;
  /** kg/m³ */
  density: number;
  /** false: no data at this wavelength (n and k are NaN) */
  valid: boolean;
  source: string;
}}

/** n, k and density of a preset at a wavelength [m], as levtrap.materials.get_material. */
export function getMaterial(name: string, wavelength: number, rtol = 2e-3): MaterialAt {{
  const m = MATERIALS[name];
  const at = (n: number, k: number, valid: boolean): MaterialAt => ({{ n, k, density: m.density, valid, source: m.source }});
  for (const [wl, n, k] of m.table) if (Math.abs(wavelength - wl) <= rtol * wl) return at(n, k, true);
  const [lo, hi] = m.sellmeier_range;
  if (m.sellmeier && lo <= wavelength && wavelength <= hi) {{
    const lu2 = (wavelength * 1e6) ** 2;
    const [B1, C1, B2, C2, B3, C3] = m.sellmeier;
    const n2 = 1 + (B1 * lu2) / (lu2 - C1) + (B2 * lu2) / (lu2 - C2) + (B3 * lu2) / (lu2 - C3);
    const k = Math.max(0, ...m.table.map((row) => row[2]));
    return at(Math.sqrt(n2), k, true);
  }}
  return at(Number.NaN, Number.NaN, false);
}}
""")
print(f"wrote {out}")
