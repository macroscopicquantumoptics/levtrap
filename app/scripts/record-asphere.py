"""Writes src/screen/asphere.fixture.ts: the engine's Result for the tweezer
with its lens replaced by the Thorlabs 354330-C (a 5 mm beam fills it), tilted by 0.3 degrees about y
(E1). The app's tests explain and export it, so they check real numbers.
    python3 scripts/record-asphere.py      (npm run record does it too)
"""

import copy
import json
import pathlib
import sys

app = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(app.parent / "src"))

from levtrap.setup import DEFAULT_SETUP  # noqa: E402
from levtrap.solve import solve  # noqa: E402

setup = copy.deepcopy(DEFAULT_SETUP)
setup["trap"]["fields"][0]["focus"] = {"kind": "asphere", "lens": "354330-C", "beam_diameter": 5e-3,
                                      "tilt_deg": [0.0, 0.3], "decentre": [0.0, 0.0]}
result = solve(setup)
result["time"] = 0
text = f"""// Generated by `npm run record` (scripts/record-asphere.py). Do not edit.
// The tweezer focused by the Thorlabs 354330-C, tilted 0.3 degrees about y.
import type {{ Result, Setup }} from "../engine/types.ts";

export const ASPHERE_SETUP: Setup = {json.dumps(setup)};

export const ASPHERE_RESULT: Result = JSON.parse({json.dumps(json.dumps(result))});
"""
(app / "src" / "screen" / "asphere.fixture.ts").write_text(text)
print("wrote src/screen/asphere.fixture.ts")
