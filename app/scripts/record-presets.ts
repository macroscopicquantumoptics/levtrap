// Records the engine's Result for every preset it computes, so the app can
// show a preset's numbers before the engine has loaded:
//   npm run record        (needs python3 with levtrap's dependencies)
// Writes src/screen/recorded.ts. src/screen/recorded.test.ts fails when the
// recording no longer matches the engine; run this again and commit.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { Result, SolveResponse } from "../src/engine/types.ts";
import { PRESETS } from "../src/screen/presets.ts";

const repo = fileURLToPath(new URL("../../", import.meta.url));
const out = fileURLToPath(new URL("../src/screen/recorded.ts", import.meta.url));
const python = process.env.PYTHON ?? "python3";
const CODE = [
  "import sys",
  "sys.path.insert(0, 'src')",
  "from levtrap.solve import solve_json",
  "print(solve_json(sys.stdin.read(), '[\"curves\"]'))",
].join("\n");

const recorded: Record<string, Result> = {};
for (const preset of PRESETS) {
  const text = execFileSync(python, ["-c", CODE], { cwd: repo, input: JSON.stringify(preset.setup), encoding: "utf8" });
  const response = JSON.parse(text) as SolveResponse;
  if (!response.ok) {
    console.log(`${preset.id}: not computed (${response.error})`);
    continue;
  }
  recorded[preset.id] = { ...response.result, time: 0 };
  console.log(`${preset.id}: recorded`);
}

// seven significant figures: more than the screen shows, and a small file
const json = JSON.stringify(recorded, (_k, v: unknown) => (typeof v === "number" ? Number(v.toPrecision(7)) : v));
const engine = Object.values(recorded)[0]?.engine ?? "unknown";
writeFileSync(
  out,
  `// Generated by \`npm run record\` (scripts/record-presets.ts) from levtrap ${engine}. Do not edit.
// The engine's Result, with force curves, for each preset it computes.
import type { Result } from "../engine/types.ts";
import type { PresetId } from "./presets.ts";

export const RECORDED: Partial<Record<PresetId, Result>> = JSON.parse(
  ${JSON.stringify(json)},
);
`,
);
console.log(`wrote ${out}`);
