// Writes src/screen/references.ts from docs/validation/references.json (C3):
// the literature setups the presets come from, by trap type.
//   node scripts/record-references.mjs        (npm run record does it too)
import { readFileSync, writeFileSync } from "node:fs";

const repo = new URL("../../", import.meta.url);
const data = JSON.parse(readFileSync(new URL("docs/validation/references.json", repo), "utf8"));
const brief = (e, status) => ({
  id: e.id,
  slot: e.slot,
  status,
  authors: e.citation.authors,
  title: e.citation.title,
  journal: e.citation.journal,
  doi: e.citation.doi ?? null,
  ...(status === "verified" ? { setup: e.setup, schema_gaps: e.schema_gaps ?? [], disagrees: e.known_disagreement?.issue ?? null } : {}),
});
const entries = [...data.verified.map((e) => brief(e, "verified")), ...data.wanted.map((e) => brief(e, "wanted"))];
const out = `// Generated by \`npm run record\` (scripts/record-references.mjs) from docs/validation/references.json. Do not edit.
import type { Reference } from "./referenceTypes.ts";

export const REFERENCES: Reference[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(new URL("app/src/screen/references.ts", repo), out);
console.log(`wrote app/src/screen/references.ts (${data.verified.length} verified, ${data.wanted.length} wanted)`);
