"""Writes src/screen/mirror.fixture.ts: the engine's Result for the tweezer
with its lens replaced by a deep parabolic mirror (f 3 mm, rim radius 9 mm,
hole radius 0.5 mm, a 10 mm beam; E3). The app's tests explain and export
it, so they check real numbers.
    python3 scripts/record-mirror.py      (npm run record does it too)
"""

import copy
import json
import pathlib
import sys

app = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(app.parent / "src"))

from levtrap.setup import DEFAULT_SETUP  # noqa: E402
from levtrap.solve import solve  # noqa: E402

setup = copy.deepcopy(DEFAULT_SETUP)
setup["trap"]["fields"][0]["focus"] = {"kind": "parabolic_mirror", "focal_length": 3e-3, "rim_radius": 9e-3,
                                      "hole_radius": 0.5e-3, "beam_diameter": 10e-3}
result = solve(setup)
result["time"] = 0
text = f"""// Generated by `npm run record` (scripts/record-mirror.py). Do not edit.
// The tweezer focused by a deep parabolic mirror: f 3 mm, rim radius 9 mm, hole radius 0.5 mm, a 10 mm beam.
import type {{ Result, Setup }} from "../engine/types.ts";

export const MIRROR_SETUP: Setup = {json.dumps(setup)};

export const MIRROR_RESULT: Result = JSON.parse({json.dumps(json.dumps(result))});
"""
(app / "src" / "screen" / "mirror.fixture.ts").write_text(text)
print("wrote src/screen/mirror.fixture.ts")
