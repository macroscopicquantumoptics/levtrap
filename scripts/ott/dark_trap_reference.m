% DARK_TRAP_REFERENCE  The bottle-beam trap of arXiv:2607.09896 computed by
% OTT itself, as a fixture for tests/test_ott_dark_trap.py.
%
% Needs MATLAB and OTT v1 (github.com/ilent2/ott, levtrap ports master @
% e6736643, v1.5.x) on the path. From the repo root:
%
%   git clone https://github.com/ilent2/ott.git /path/to/ott
%   git -C /path/to/ott checkout e6736643
%   matlab -batch "addpath('/path/to/ott'); run('scripts/ott/dark_trap_reference.m')"
%
% Writes tests/fixtures/ott_dark_trap.json. Everything here is computed by
% OTT, independently of levtrap: the waist -> angle mapping (OTT's
% paraxial_beam_waist), the power split that nulls the field at the focus,
% the coherent sum, the beam coefficients, the Mie T-matrix and the forces.
% The inputs are the paper's as levtrap reads them (examples/paper_2607_09896.py):
% two circular(+) LG beams at 1550 nm in vacuum, LG00 w = 1.59 um and LG10
% w = 0.866 um with phase pi, 0.8 W combined; WS2 n = 3.79 + 2.83e-10i.

wl = 1550e-9; n_med = 1.0; Ptot = 0.8; pol = [1 1i];
waists = [1.59e-6, 0.866e-6]; modes = [0 0; 1 0]; phases = [0 pi];
radius = 298e-9; n_p = 3.79 + 2.83e-10i;

% waist -> convergence angle: tan(theta) = lambda w_p / (pi w)
angles = zeros(1, 2);
for i = 1:2
  order = 2*modes(i,1) + abs(modes(i,2));
  angles(i) = atan(wl/n_med * ott.utils.paraxial_beam_waist(order) / (pi*waists(i)));
end

warning('off', 'all');  % OTT warns whenever 'power' is set
for i = 1:2
  beams{i} = ott.BscPmGauss('lg', modes(i,:), 'polarisation', pol, 'angle', angles(i), ...
      'index_medium', n_med, 'wavelength0', wl, 'power', 1.0);
end

% split that nulls the focal field: P1 |E1(0)|^2 = P2 |E2(0)|^2 (unit-power beams)
e = zeros(1, 2);
for i = 1:2
  E = beams{i}.emFieldXyz([0; 0; 0]);
  e(i) = sum(abs(E(:)).^2);
end
split = [e(2), e(1)] / (e(1) + e(2));

beam = beams{1} * (sqrt(Ptot*split(1)) * exp(1i*phases(1))) ...
     + beams{2} * (sqrt(Ptot*split(2)) * exp(1i*phases(2)));
beam = beam * sqrt(Ptot / beam.power);   % 0.8 W is the power of the combined beam

T = ott.TmatrixMie(radius, 'index_medium', n_med, 'index_particle', n_p, 'wavelength0', wl);

z = linspace(-1.5e-6, 1.5e-6, 61);
fz = ott.forcetorque(beam, T, 'position', [zeros(size(z)); zeros(size(z)); z]);
x = linspace(-0.6e-6, 0.6e-6, 25); zx = 0.236e-6;   % radial cut near levtrap's z_eq
fx = ott.forcetorque(beam, T, 'position', [x; zeros(size(x)); zx*ones(size(x))]);

[st, commit] = system(['git -C "' fileparts(fileparts(which('ott.BscPmGauss'))) '" rev-parse HEAD']);
if st ~= 0, commit = 'unknown'; end

out = struct();
out.about = ['OTT v1 reference for the dark trap of arXiv:2607.09896; ' ...
             'generated by scripts/ott/dark_trap_reference.m'];
out.ott_commit = strtrim(commit);
out.matlab = version;
out.inputs = struct('wavelength', wl, 'medium_index', n_med, 'power', Ptot, 'waists', waists, ...
    'modes', modes, 'phases', phases, 'radius', radius, 'n', real(n_p), 'k', imag(n_p));
out.angles = angles;
out.split = split;
out.Nmax = beam.Nmax;
a = full(beam.a); b = full(beam.b);
out.a_re = real(a)'; out.a_im = imag(a)'; out.b_re = real(b)'; out.b_im = imag(b)';
out.axial = struct('z', z, 'force', fz);           % rows fx, fy, fz
out.radial = struct('z', zx, 'x', x, 'force', fx);

here = fileparts(mfilename('fullpath'));
f = fopen(fullfile(here, '..', '..', 'tests', 'fixtures', 'ott_dark_trap.json'), 'w');
fprintf(f, '%s\n', jsonencode(out, 'PrettyPrint', true));
fclose(f);
fprintf('angles (deg) %.6f %.6f, split %.6f : %.6f, Nmax %d\n', angles*180/pi, split, beam.Nmax);
